"""Step 3: User Funnel Conversion Analysis Query"""

query_funnel = """
WITH funnel_counts AS (
    SELECT
        COUNT(DISTINCT CASE WHEN event_type = 'view' THEN user_id END) AS unique_viewers,
        COUNT(DISTINCT CASE WHEN event_type = 'cart' THEN user_id END) AS unique_carters,
        COUNT(DISTINCT CASE WHEN event_type = 'purchase' THEN user_id END) AS unique_buyers
    FROM events
)
SELECT
    unique_viewers,
    unique_carters,
    unique_buyers,
    ROUND(CAST(unique_carters AS FLOAT) / unique_viewers * 100, 2) AS view_to_cart_pct,
    ROUND(CAST(unique_buyers AS FLOAT) / unique_carters * 100, 2) AS cart_to_purchase_pct,
    ROUND(CAST(unique_buyers AS FLOAT) / unique_viewers * 100, 2) AS overall_conversion_pct
FROM funnel_counts;
"""

funnel_df = pd.read_sql_query(query_funnel, conn)
funnel_df

import matplotlib.pyplot as plt

# 1. Save funnel data to CSV
funnel_df.to_csv('user_conversion_funnel.csv', index=False)

# 2. Prepare data for funnel visualization
stages = ['Viewers', 'Carters', 'Buyers']
counts = [funnel_df['unique_viewers'][0], funnel_df['unique_carters'][0], funnel_df['unique_buyers'][0]]
colors = ['#1f77b4', '#ff7f0e', '#2ca02c']

plt.figure(figsize=(8, 5))
bars = plt.bar(stages, counts, color=colors, width=0.5)
plt.title('User Conversion Funnel Stages', fontsize=14, pad=12)
plt.ylabel('Unique Users', fontsize=11)
plt.grid(axis='y', linestyle='--', alpha=0.5)

# Add count labels on top of each bar
for bar in bars:
    height = bar.get_height()
    plt.text(bar.get_x() + bar.get_width()/2., height + 150, f'{height:,}',
             ha='center', va='bottom', fontsize=10, fontweight='bold')

plt.tight_layout()

# Save plot image
plt.savefig('user_conversion_funnel.png', dpi=300)
plt.show()

